_SEPARATORS = re.compile(r"[\\/]")

# Символы, которых Windows не пускает в имя файла или папки. Косые черты и
# двоеточие разобраны отдельно (вложенная категория, буква диска), остальное
# ловится здесь. Управляющие символы в конце набора приходят не с клавиатуры, а
# из склеенной программой строки — и ломают имя так же.
_FORBIDDEN_IN_NAME = re.compile(r'[<>:"|?*\x00-\x1f]')


def name_key(name: str) -> str:
    """Имя файла или папки в виде, пригодном для сравнения с тем, что на диске.

    Windows считает `Медиа` и `медиа` одной и той же папкой, а `mkdir` не
    переименовывает уже существующую: стоит ей появиться раньше в другом
    регистре — от прошлой версии правил, от руки, от другой программы, — и
    файлы молча укладываются в неё. Снаружи всё в порядке: план показан, файлы
    разложены. А сверка с `managed_folders` шла строка в строку, поэтому такая
    папка переставала быть своей: «Переразложить старое» в неё не заходило,
    новые категории до лежащего внутри не доезжали никогда, и пустой её никто
    не убирал. Чёрная дыра ровно того вида, о котором предупреждает
    `_check_managed`, — только заметить её нечем.

    Правило это задаёт файловая система, а не то, папка перед нами или файл,
    поэтому им же сверяются ключи `overrides.json` (`classifier.find_override`):
    ручное правило пишут, глядя на имя в проводнике, а проводник показывает его
    как хочет.

    `os.path.normcase` делает нужное и ровно там, где нужно: на Windows
    приводит регистр, на Linux и macOS оставляет имя как есть — там `Медиа` и
    `медиа` и правда разные имена, и считать их одним было бы уже вторжением
    в чужое.
    """
    return os.path.normcase(name)


def folder_key(name: str) -> str:
    """Имя папки для сравнения. То же, что `name_key`, — правило задаёт ФС."""
    return name_key(name)


def folder_keys(names) -> set[str]:
    """Набор имён папок для сравнения (см. `folder_key`)."""
    return {folder_key(name) for name in names}


def root_folder_keys(config) -> set[str]:
    """Имена папок, которые программа создаёт прямо в корне загрузок.

    Это категории и только они. Раскладка у программы строгая —
    `Категория/Тип/файл`, — и имя типа (`Code`, `Models`, `Documents`,
    `Images`) в корне загрузок она не создаёт никогда.

    Обход до сих пор решал «своё или чужое» по одному плоскому
    `managed_folders`, где свалены и категории, и типы, — и на корне это
    нарушало главное обещание программы. Распакованный архив `Models` (так
    называют свои папки модели Stable Diffusion), репозиторий `Code`, папка
    `Documents` из чужого дистрибутива по имени неотличимы от папок программы,
    и «Переразложить старое» растаскивало их содержимое по категориям:
    `Code/main.py` уезжал в `Код/Code/`, `Code/LICENSE` — в `Others/Misc/`,
    а от папки, которую человек распаковал целиком, оставалась пустая
    скорлупа. README про это говорит прямо: «Чужая папка — единица, а не набор
    файлов; разложив её содержимое по типам, программа уничтожила бы её
    целиком», и подсказка самой галочки обещает, что чужие папки не трогаются
    в любом случае.

    Глубже корня список по-прежнему плоский, и это верно: внутри `Код` папка
    `Code` — своя, её создала программа.

    Вложенная категория (`Учёба/2026`) стоит в корне первым куском имени —
    берём его. Сверяемся с `managed_folders`: категория, не получившая там
    строки, своей не считается и в корне (об этом отдельно говорит
    `_check_managed`).
    """
    names = [*config.categories, *config.patterns,
             *config.overrides.values(), config.fallback_category]
    heads = {folder_key(_SEPARATORS.split(name)[0]) for name in names if name}
    return heads & folder_keys(config.managed_folders)


def usable_3d_path(raw) -> bool:
    """Годится ли строка как путь внешней папки 3D.

    С категорией всё наоборот: там путь, вписанный вместо имени папки, уносит
    файлы из загрузок неизвестно куда (`folder_name_problem`). Здесь ждут именно
    путь — и неполный опасен ровно тем же. `Path("All_3d")` считается от
    рабочей папки, а у ярлыка она какая угодно: папка программы, рабочий стол,
    последняя папка проводника. Модели уезжают туда, куда никто не смотрит.

    Заметить это нечем: план показывает `All_3d\\stl\\деталь.stl` — строку,
    неотличимую от папки внутри загрузок. Имя без диска попадает в настройку
    легко: опечатка при правке `config.json` руками, набранное вручную поле
    вместо «Обзор…», перенос конфига с другой машины.

    `C:` без косой черты тоже неполный: Windows считает от текущей папки на
    диске C, и это снова не то место, которое имели в виду.
    """
    return isinstance(raw, str) and bool(raw) and Path(raw).is_absolute()


def path_3d_reason(raw) -> str:
    """Что не так с путём внешней папки 3D. Пустая строка — всё в порядке.

    Причина живёт здесь одна на всех, потому что говорят о ней в двух местах:
    при чтении настроек (жалоба на файл, её показывают окна при старте) и при
    построении плана (`planner.external_3d_warning` — про этот конкретный
    прогон, где галочку мог перебить флаг `--to3d`). Консоль печатает и то, и
    другое подряд, и без общего куска текста она повторяла бы одно и то же
    двумя разными фразами.
    """
    if usable_3d_path(raw):
        return ""
    if not raw:
        return "путь к папке не указан"
    return f"путь «{raw}» неполный — по нему не видно ни диска, ни папки"


def extension_key(value) -> str:
    """Расширение в том виде, в каком его отдаёт `classifier.extension_of`.

    То есть без точки, без пробелов по краям и в нижнем регистре. Одно место
    на всех, кто сверяет расширения: `type_map`, `external_3d.extensions` и
    проверка правил-призраков. Раньше такое приведение знал только список
    выноса 3D, а `match_type` сравнивал строка в строку, и `".pdf"`, написанное
    в `type_map` после правки руками, не совпадало с `"pdf"` ни разу — все
    документы молча уезжали в запасной тип. Тот же исход, что у `"PDF"`
    заглавными до починки регистра, и приходит он тем же путём: три написания
    одного и того же живут в этом проекте рядом.
    """
    return str(value).strip().lstrip(".").lower()


def clean_extensions(raw) -> list[str]:
    """Расширения в том виде, в каком их отдаёт `classifier.extension_of`.

    То есть без точки, в нижнем регистре и без пустых записей. Приводить
    приходится потому, что в одном проекте живут три разных написания одного и
    того же: слова категорий пишутся с точкой (`".stl"`), `type_map` — без
    (`"stl"`), а `external_3d.extensions` сверяется с расширением файла, то есть
    тоже без. Написать `".stl"` в настройках после правки rules.json руками —
    самая обычная ошибка, и она была из тех, что не видно: сверка шла с
    расширением без точки, не совпадало ничего, и вынос 3D переставал выносить.
    Ни ошибки, ни предупреждения — путь-то годный, галочка стоит, план построен.

    Пустая строка выбрасывается по той же причине, что и пустое слово в
    `_rule_map`, только исход у неё другой: `extension_of` отдаёт пустую строку
    для файла без расширения, и такая запись увела бы во внешнюю папку 3D все
    файлы без расширения разом.
    """
    good: list[str] = []
    for value in raw:
        text = extension_key(value)
        if text and text not in good:
            good.append(text)
    return good


def external_3d_extensions(external_3d) -> set[str]:
    """Расширения, которые едут во внешнюю папку 3D, в виде `extension_of`.

    Читателей у этого списка двое и они далеко друг от друга: планировщик
    решает, кому место выбирает расширение, а обход решает, какая подпапка
    внутри All_3d создана программой, а какая человеком. Считать одно и то же
    двумя способами тут нельзя — разойдясь, они начнут спорить о судьбе одного
    и того же файла.

    Приведение дублирует `Config.load` нарочно: конфиг собирают и напрямую — из
    тестов, из CLI, — а сверять `".stl"` из настроек с `"stl"` из имени файла
    значит не совпасть ни разу и промолчать об этом. Не список (`"stl"` вместо
    `["stl"]` после правки руками) — это «списка нет»: перебор строки по буквам
    выдал бы расширения `s`, `t`, `l`.
    """
    if not isinstance(external_3d, dict):
        return set()
    raw = external_3d.get("extensions", [])
    if not isinstance(raw, list):
        return set()
    return set(clean_extensions(raw))


def folder_name_problem(value: str, noun: str = "имя папки") -> str:
    """Почему строка не годится именем папки. Пустая строка — годится.

    Категория и тип уходят прямо в `root / категория / тип`, а `Path` устроен
    так, что абсолютный кусок отбрасывает всё слева: `Path("D:/Загрузки") /
    "C:/Windows/Temp"` — это просто `C:/Windows/Temp`. Значит, полный путь,
    вписанный вместо категории (опечатка, вставка не в то поле, правка руками),
    молча уносит файлы из загрузок совсем в другое место. `..` делает то же
    самое. Это худший исход из возможных: программа отчитывается об успешной
    сортировке, а файлов в загрузках больше нет и искать их негде.

    Второй случай — имя, которое файловая система запишет не так, как написано.
    Windows отрезает у имени папки хвостовые пробелы и точки, и обе половины
    этого выходят плохо. `"Учёба "`: план строится обычный, а перемещения
    падают все до одного — `mkdir` создаёт `Учёба`, `shutil.move` ищет
    `Учёба \\Documents` и получает `[WinError 3]`; в загрузках остаётся
    неразобранный файл и пустая папка, которую никто не просил. `"Учёба."` —
    ещё хуже, потому что тише: перемещение проходит, отчёт рапортует успех, а
    файлы лежат в `Учёба`, которой нет ни в `managed_folders`, ни где-либо ещё.
    Своей она не считается, «Переразложить старое» в неё не заходит, пустой её
    не убирает — чёрная дыра, и предупредить о ней нечем: имя-то в правилах
    написано, проверка `_check_managed` видит именно его.

    Имя из одних пробелов не создаётся вовсе и попадает сюда же.

    Пробел в начале имени — тот же случай наизнанку, и он тише всех прочих.
    Хвостовой файловая система отрезает, и потому хоть как-то себя выдаёт:
    перемещения падают или файлы оказываются в соседней папке. Ведущий она
    сохраняет как есть — то есть создаёт настоящую отдельную папку ` Учёба`,
    на вид неотличимую от `Учёба`. В `managed_folders` её нет, значит
    «Переразложить старое» в неё не заходит, пустой её никто не убирает, а
    новые правила до лежащего внутри не доезжают никогда. Увидеть это в
    проводнике нельзя: две такие папки стоят рядом и выглядят одинаково.
    Приходит пробел обычным путём — копипаст имени из README, правка руками,
    съехавшая кавычка в JSON.

    Считаем по `strip`, а не по одному пробелу: неразрывный пробел (`\\xa0`)
    прилетает копипастом с веб-страницы, Windows его тоже не отрезает, и папка
    получается ровно такая же отдельная и невидимая.

    Третий случай — символ, которого Windows в имени не разрешает вовсе:
    `? * " < > |` и всё, что ниже пробела. Исход тут третий и самый шумный:
    план строится обычный, а `mkdir` падает с `[WinError 123]` на каждом файле
    подряд — не переезжает ни один. Отчёт при этом честный, ошибки названы
    поимённо, вот только говорят они про папку назначения, а не про строку в
    правилах, из-за которой её нельзя создать. Приходит такой символ обычным
    путём: `Отчёты?`, `Скриншоты*`, `Учёба: 2026` — двоеточие в первой части
    имени ловится проверкой выше как буква диска, а во второй (`Учёба/2026:
    год`) не ловилось ничем.

    Вложенная категория (`Учёба/2026`) — обычное дело, её не трогаем.
    """
    parts = [p for p in _SEPARATORS.split(value) if p]
    if (not parts or value[0] in "\\/" or ":" in parts[0]  # буква диска
            or ".." in parts or "." in parts):
        return f"это путь, а не {noun}"
    forbidden = _FORBIDDEN_IN_NAME.search(value)
    if forbidden:
        shown = repr(forbidden.group())[1:-1]  # управляющий символ — как \x01
        return (f"это не {noun}: символ «{shown}» файловая система в имени "
                "не разрешает, папка не создастся")
    if any(not part.strip() or part != part.rstrip(" .") for part in parts):
        return (f"это не {noun}: хвостовые пробелы и точки файловая система "
                "отрезает, и папка получится другая")
    if any(part != part.strip() for part in parts):
        return (f"это не {noun}: пробел по краю имени файловая система "
                "сохранит, и папка получится отдельная, а на вид та же самая")
    return ""


def _read_json(path: Path, problems: list[str]) -> dict | None:
    """Читает JSON. При поломке возвращает None и дописывает жалобу в problems.

    Молча подставить пустоту нельзя: без правил всё уедет в Others, и это надо
    показать пользователю до того, как он нажмёт «Применить».

    Кодировку разбирает общий декодер (`util.decode_text`), а не жёсткое
    `encoding="utf-8"`. Все три файла README предлагает править руками, а
    «руками» на Windows — это Блокнот с его «UTF-8 с BOM», «UTF-16 LE» и
    «ANSI» и PowerShell 5.1, у которого `Out-File` пишет UTF-16 по умолчанию.
    Любой из этих файлов объявлялся нечитаемым целиком: BOM для `json` не
    пробел, а неожиданный символ, UTF-16 не декодируется вовсе. Жалоба при
    этом называла причину неверно — «Expecting value: line 1 column 1», то
    есть отправляла искать опечатку в JSON, которой там нет.
    """
    if not path.exists():
        return None
    try:
        data = json.loads(read_text(path))
    except (OSError, ValueError) as exc:
        problems.append(f"{path.name}: не читается ({exc}). Файл пропущен.")
        return None
    if not isinstance(data, dict):
        problems.append(f"{path.name}: ожидался объект JSON. Файл пропущен.")
        return None
    return data


def _clean_3d(raw, problems: list[str]) -> dict:
    """Приводит настройку внешней папки 3D к словарю с полным набором ключей.

    Читателей у этой настройки пятеро: планировщик, оба окна и две проверки
    пути. Раньше половина звала `.get` прямо, а половина сначала проверяла тип —
    и строка вместо объекта (`"external_3d": "C:/All_3d"` после правки руками)
    роняла программу на запуске, даже когда вынос 3D был выключен. Разбираемся
    с этим здесь, один раз, чтобы дальше все читатели имели дело со словарём.
    """
    if not isinstance(raw, dict):
        if raw:
            problems.append(
                "config.json: external_3d — не объект. Настройка 3D сброшена.")
        # Расширения нужны и здесь. Пустой словарь — это не только «правку
        # руками не разобрали», это ещё и обычный config.json нового
        # пользователя, где ключа `external_3d` нет вовсе. Такой словарь
        # доезжал до планировщика без списка расширений, и первая же попытка
        # включить вынос 3D прямо в окне — галочка, путь через «Обзор…» —
        # не выносила ни одного файла: совпадать было не с чем. Ни ошибки, ни
        # предупреждения: путь-то годный, `external_3d_warning` молчит. Само
        # чинилось только после закрытия и повторного открытия окна, потому
        # что `save` дописывает расширения на выходе. Ветка ниже давно
        # подставляет их для словаря без ключа — здесь было то же самое
        # упущение, только этажом выше.
        return {"extensions": list(DEFAULT_3D_EXTENSIONS)}
    data = dict(raw)
    extensions = data.get("extensions")
    if extensions is not None and not isinstance(extensions, list):
        # `"extensions": "stl"` вместо `["stl"]` — правка руками, перенос
        # настроек с другой машины, съехавшие скобки. Раньше такая запись
        # молча заменялась полным списком по умолчанию, то есть делала ровно
        # обратное написанному: человек сужал вынос до одного расширения, а
        # получал все четыре, и модели уезжали из загрузок пачками. Соседний
        # случай — список, в котором после чистки не осталось ничего — назван
        # вслух давно и по той же причине.
        problems.append(
            "config.json: external_3d.extensions — не список. Взят список по "
            "умолчанию: " + ", ".join(DEFAULT_3D_EXTENSIONS) + ".")
    cleaned = clean_extensions(extensions) if isinstance(extensions, list) else []
    if not cleaned:
        # Список был, но пригодного в нём не осталось: внутри лежали одни пустые
        # строки — или список пуст с самого начала. Молча взять список по
        # умолчанию нельзя: человек ограничивал вынос нарочно, а получил бы все
        # расширения сразу, то есть ровно обратное написанному.
        #
        # Про пустой список (`"extensions": []`) раньше не говорилось ни слова,
        # хотя приходит он тем же путём — недописанная правка, стёртые
        # строки, — и делает ровно то же самое. Проверка стояла на списке из
        # пустых строк и обходила стороной случай, где стирать уже нечего.
        if isinstance(extensions, list):
            problems.append(
                "config.json: external_3d.extensions — ни одного пригодного "
                "расширения. Взят список по умолчанию: "
                + ", ".join(DEFAULT_3D_EXTENSIONS) + ".")
        cleaned = list(DEFAULT_3D_EXTENSIONS)
    data["extensions"] = cleaned
    # Путь уходит и в `Path()`, и в поле ввода — обоим нужна строка. Проверка
    # самой настройки на «объект» тут не помогает: объект может быть правильный,
    # а путь внутри — числом после съехавшей замены в редакторе. Программа тогда
    # не открывалась вовсе, то есть починить настройку через окно уже нельзя.
    path = data.get("path")
    if path is not None and not isinstance(path, str):
        problems.append(
            "config.json: external_3d.path — не строка. Путь к папке 3D сброшен.")
        data["path"] = ""
    elif isinstance(path, str):
        # Пробелы по краям — та же история, что у папки загрузок, только исход
        # другой и хуже. Спереди: `Path(" C:/All_3d").is_absolute()` — False, и
        # человек читает «по этому пути не видно ни диска», глядя на путь, где
        # диск написан. Сзади: путь считается годным, предупреждения нет, план
        # показывает `All_3d \stl\деталь.stl` — строку, от исправной не
        # отличимую, — а `All_3d ` в середине пути Windows не находит, и каждая
        # модель остаётся в загрузках с `[WinError 3]` в отчёте.
        data["path"] = path.strip()
    # Галочку читают через `bool(...)` все пятеро, и потому `"false"` строкой
    # значит «включено»: непустая строка истинна. Человек, поправивший
    # `config.json` руками, получает ровно обратное тому, что написал — модели
    # уезжают из загрузок, галочка в окне стоит, жалоб нет. Соседние поля этой
    # же настройки давно проверяются по типу, эта — нет.
    #
    # Спорное значение гасим, а не угадываем: включённый вынос двигает файлы за
    # пределы загрузок, и ошибиться в эту сторону дороже. Сказано об этом
    # вслух, а поставить галочку обратно можно прямо в окне.
    enabled = data.get("enabled")
    if enabled is not None and not isinstance(enabled, bool):
        problems.append(
            f"config.json: external_3d.enabled — не «да/нет», а «{enabled}». "
            "Вынос 3D выключен.")
        data["enabled"] = False
    # Галочка стоит, а пути нет — и планировщик ведёт себя ровно так, будто
    # галочки тоже нет: `external_3d_path` без годного пути отдаёт None, и
    # модели едут в обычные категории. Снаружи это неотличимо от исправной
    # работы: настройка включена, план построен, жалоб никаких. Тот же исход,
    # что у забытого `extensions` парой строк выше, — настройка выглядит
    # рабочей, но не выносит ничего.
    #
    # Неполный путь до этой правки вёл себя иначе и хуже: он работал, но не
    # туда. Теперь он приравнен к «пути нет» — но сказать о нём надо отдельно,
    # потому что в поле ввода такой путь на вид совершенно исправен.
    reason = path_3d_reason(data.get("path"))
    if data.get("enabled") and reason:
        problems.append(
            f"config.json: вынос 3D включён, но {reason}. "
            "Модели поедут в обычные категории.")
    return data


def _rule_map(raw, where: str, key: str, problems: list[str]) -> dict[str, list[str]]:
    """Раздел вида «категория → список слов» (`categories`, `patterns`, `type_map`).

    Правила README предлагает править руками, а отсюда они уходят прямо в
    `.items()`: раздел списком вместо объекта ронял программу на первом же
    файле. Список слов строкой не ронял ничего — и это хуже: `"Медиа": "клип"`
    перебирается по буквам, каждая работает как ключевое слово, и в «Медиа»
    уезжает вообще всё. Молчаливую неверную раскладку замечают, когда файлы
    уже разложены, поэтому такой раздел выбрасываем с жалобой.

    Пустая строка внутри списка делает ровно то же самое и приходит тем же
    путём — недописанная правка, стёртое слово, список, собранный скриптом.
    `match_category` ищет вхождение подстроки, а пустая строка входит в любое
    имя: первая же категория с такой записью забирает себе всю папку загрузок.
    Отличить это от исправной работы нельзя ничем — план построен, файлы
    разложены, жалоб нет, и в предпросмотре у каждой строки честная пометка
    «слово», та самая, которой README велит доверять. У шаблонов пустое
    выражение подходит к любому имени и бьёт ещё раньше (они проверяются до
    слов), а в `type_map` пустая строка равна расширению файла без расширения
    и выдаёт таким файлам настоящий тип вместо запасного.
    """
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        problems.append(f"{where}: {key} — не объект. Раздел пропущен.")
        return {}
    good: dict[str, list[str]] = {}
    for name, values in raw.items():
        if not isinstance(name, str):
            continue
        # Имя раздела — это имя папки: категория или тип. Путь вместо него
        # уводит файлы из загрузок, а имя с хвостовым пробелом или точкой
        # файловая система запишет по-своему (см. `folder_name_problem`).
        trouble = folder_name_problem(name)
        if trouble:
            problems.append(f"{where}: {key} → «{name}» — {trouble}. Пропущено.")
            continue
        if not isinstance(values, list):
            problems.append(f"{where}: {key} → «{name}» — не список. Пропущено.")
            continue
        kept: list[str] = []
        for value in values:
            if not isinstance(value, str):
                continue
            # Строка из одних пробелов делает то же, что пустая, и приходит
            # тем же путём. Пробел есть в имени большинства скачанных файлов,
            # так что категория с такой записью забирает себе почти все
            # загрузки, а в `type_map` пробел равен расширению файла, у
            # которого расширения нет. Пробелы ВНУТРИ слова не трогаем: `" фон "`
            # — это приём, способ потребовать границы слова, а не опечатка.
            if not value.strip():
                problems.append(
                    f"{where}: {key} → «{name}»: пустая строка вместо слова. "
                    "Она подходит к любому файлу — пропущена.")
                continue
            kept.append(value)
        good[name] = kept
    return good


def _pattern_map(raw, where: str, key: str, problems: list[str]) -> dict[str, list[str]]:
    """Раздел `patterns`: то же, что `_rule_map`, плюс проверка самих выражений.

    Регулярку пишут руками, и опечатка в ней — лишняя скобка, незакрытый класс,
    забытая фигурная скобка — не роняет ничего: `match_pattern` ловит `re.error`
    и идёт дальше. В этом и беда. Снаружи битое выражение выглядит как исправное
    правило, которое почему-то ни разу не сработало: скриншоты уезжают в Others,
    план построен, жалоб нет. Проверить нечем — пометку «шаблон» предпросмотр
    ставит только когда шаблон подошёл, а «не опознан» ничем не отличается от
    честного «такого правила и не было».

    Битое выражение поэтому выбрасываем здесь и говорим о нём вслух. Соседние
    выражения той же категории остаются: одна опечатка не должна уносить с собой
    работающие шаблоны. Проверку в `match_pattern` не снимаем — конфиг собирают
    и напрямую, из тестов и из CLI.
    """
    good = _rule_map(raw, where, key, problems)
    for name, expressions in good.items():
        checked: list[str] = []
        for expression in expressions:
            try:
                re.compile(expression)
            except re.error as exc:
                problems.append(
                    f"{where}: {key} → «{name}»: выражение «{expression}» "
                    f"не разбирается ({exc}). Пропущено.")
                continue
            checked.append(expression)
        good[name] = checked
    return good


def _text_map(
    raw, where: str, key: str, problems: list[str], folders: bool = False
) -> dict[str, str]:
    """Раздел вида «имя → строка» (`overrides`, `category_hints`).

    Категория из `overrides.json` уходит в `Path()`, и число вместо неё роняло
    построение плана целиком — и в окне, и в CLI.

    `folders=True` — значение станет именем папки (так у `overrides`). Тогда
    отбраковывается и путь вместо категории (файл уехал бы из загрузок
    неизвестно куда), и имя, которое файловая система запишет по-своему, —
    см. `folder_name_problem`. Подсказки категорий (`category_hints`) — обычный
    текст, там проверять нечего.

    Пустая категория тоже отбраковывается — и по той же причине, по какой
    отбраковывают битую регулярку: запись выглядит правилом, а правилом не
    является. `explain_category` берёт её через `or`, то есть проваливается
    дальше к шаблонам и словам, зато окно ИИ смотрит на само наличие ключа —
    и ответ модели про такое имя выбрасывает, «сберегая» несуществующее
    правило. Имя при этом в запрос уходит (`_has_rule` пустую строку правилом
    не считает): деньги платятся, ответ выбрасывается, окно отчитывается
    «свои правила сохранены», а файл остаётся неразобранным навсегда.
    """
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        problems.append(f"{where}: {key} — не объект. Раздел пропущен.")
        return {}
    good: dict[str, str] = {}
    for name, value in raw.items():
        if not isinstance(name, str) or not isinstance(value, str):
            problems.append(f"{where}: запись «{name}» — не строка. Пропущена.")
            continue
        if folders and not value:
            problems.append(
                f"{where}: «{name}» → категория не названа. "
                "Такая запись ничего не решает. Пропущена.")
            continue
        trouble = folder_name_problem(value, "категория") if folders else ""
        if trouble:
            problems.append(f"{where}: «{name}» → «{value}» — {trouble}. Пропущено.")
            continue
        good[name] = value
    return good


def _text_list(raw, where: str, key: str, problems: list[str]) -> list[str]:
    """Список строк (`managed_folders`, `ignore`). Не список — пустой список."""
    if raw is None:
        return []
    if not isinstance(raw, list):
        problems.append(f"{where}: {key} — не список. Раздел пропущен.")
        return []
    return [v for v in raw if isinstance(v, str)]


def _trim_managed(names: list[str], where: str, problems: list[str]) -> list[str]:
    """Срезает пробелы по краям имён в `managed_folders`. О срезанном говорит.

    Своя папка опознаётся сверкой имени по правилам файловой системы, а имени
    с хвостовым пробелом на диске не бывает: Windows его отрезает. Значит
    запись `"Медиа "` не совпадёт с настоящей `Медиа` никогда, и папка
    перестаёт быть своей — «Переразложить старое» в неё не заходит, пустой её
    никто не убирает, новые правила до лежащего внутри не доезжают. Ровно та
    чёрная дыра, о которой предупреждает `_check_managed`, только пришедшая с
    другой стороны: категория-то написана правильно.

    Хуже последствий сама жалоба. `_check_managed` скажет «категория «Медиа»
    не указана в managed_folders», человек посмотрит в файл и увидит там
    `Медиа` — сообщение выглядит враньём, и искать в нём невидимый пробел
    никому в голову не придёт. Отличить одно от другого можно только сравнив
    длины двух одинаковых на вид строк.

    Поэтому здесь не отбраковка, а срезка: пути к загрузкам и к папке 3D
    подчищаются точно так же и по той же причине. Имя папки с пробелом по краю
    правилами больше не считается вовсе (`folder_name_problem`), так что терять
    тут нечего — а от записи, оставшейся из одних пробелов, толку нет никакого,
    и её выбрасываем.
    """
    trimmed: list[str] = []
    for name in names:
        clean = name.strip()
        if clean == name:
            trimmed.append(name)
            continue
        problems.append(
            f"{where}: managed_folders → «{name}» написана с пробелом по краю. "
            "С настоящей папкой такое имя не совпадёт никогда"
            + (f" — взято «{clean}»." if clean else ", и срезать нечего. Пропущено."))
        if clean:
            trimmed.append(clean)
    return trimmed


def _text(raw, default: str, where: str, key: str, problems: list[str]) -> str:
    """Имя запасной папки (`fallback_category`/`fallback_type`).

    Сюда попадает всё, что не опознано, — то есть путь вместо запасной категории
    утащил бы из загрузок не один файл, а весь неопознанный хвост.
    """
    if raw is None:
        return default
    if not isinstance(raw, str) or not raw:
        problems.append(f"{where}: {key} — не строка. Взято «{default}».")
        return default
    trouble = folder_name_problem(raw)
    if trouble:
        problems.append(f"{where}: {key} — {trouble}. Взято «{default}».")
        return default
    return raw


def _drop_frozen_rules(
    overrides: dict[str, str], fallback: str, where: str, problems: list[str]
) -> dict[str, str]:
    """Убирает ручные правила, ведущие в запасную категорию.

    Такое правило — это записанное «не знаю», и вреда от него ровно столько же,
    сколько пользы: без него файл уедет в ту же запасную папку, но по текущим
    правилам, а с ним — по прошлогоднему решению и мимо всего, что появилось
    потом. Правило стоит выше шаблонов и слов (`explain_category`), поэтому
    закрывает дорогу навсегда: сколько категорию ни улучшай, файл до неё не
    дойдёт.

    Ровно это и случилось с рендерами Blender. Их опознаёт шаблон
    `^\\d{4}-\\d{4}\\.(mp4|...)$` — диапазон кадров, имя, которое словом не
    выразить, — но в `overrides.json` со старых времён лежало три десятка
    записей `0001-0250.mp4 → Others`, и до шаблона дело не доходило ни разу.
    Снаружи это неотличимо от исправной работы: план построен, жалоб нет, в
    предпросмотре у каждой строки честная пометка «правило» — та самая,
    которой README велит доверять больше прочих.

    `ai.useful_rules` не даёт записать такое правило от модели, и это стоит на
    записи с тех пор, как фильтр появился. А правила, попавшие в файл раньше
    (или дописанные руками), читались как обычные: проверка была ровно с одной
    стороны.

    Сверяемся по правилам файловой системы (`folder_key`): `others` и `Others`
    на Windows — одна и та же папка, и правило, набранное не тем регистром,
    морозит файл точно так же.
    """
    frozen = [name for name, category in overrides.items()
              if folder_key(category) == folder_key(fallback)]
    if not frozen:
        return overrides
    shown = ", ".join(f"«{name}»" for name in frozen[:3])
    tail = f" и ещё {len(frozen) - 3}" if len(frozen) > 3 else ""
    problems.append(
        f"{where}: правила в запасную категорию «{fallback}» пропущены "
        f"({len(frozen)} шт.: {shown}{tail}). Такое правило ничего не решает — "
        f"без него файл уедет в «{fallback}» сам, — а в новую категорию "
        "не пускает никогда.")
    return {name: category for name, category in overrides.items()
            if name not in set(frozen)}


def _check_managed(
    categories: list[str],
    types: list[str],
    managed: list[str],
    where: str,
    problems: list[str],
) -> None:
    """Жалуется на категории и типы, которых нет в `managed_folders`.

    Файл уезжает в `Загрузки/Категория/Тип`, но обратно программа заходит
    только в свои папки — те, чьё имя есть в `managed_folders`. Категория, эту
    строку не получившая, работает ровно один раз: файлы в неё складываются
    нормально, а дальше папка становится чёрной дырой. «Переразложить старое»
    её не видит, значит новые правила к лежащему внутри уже не применятся
    никогда. Опустевшей её тоже никто не уберёт.

    Заметить это невозможно: раскладка выглядит правильной, жалоб нет, а
    последствия вылезают через месяц и совсем в другом месте. Ровно этот исход
    README разбирает на переименованной `fallback_category` — там его починили
    поимённо, а общей проверки не было. Правила README предлагает править
    руками, и забыть вторую строку при добавлении категории — самая обычная
    ошибка: `categories` и `managed_folders` лежат в файле далеко друг от друга.

    Вложенная категория (`Учёба/2026`) — это две папки, и обход спускается по
    ним по очереди, поэтому нужны обе.

    Пустой список — это не «списком не пользуются», а «своей не считается ни
    одна папка», и разница тут вся. Долгое время он молча пропускался с мыслью,
    что жалоба на каждую категорию завалила бы окно шумом; шум и правда ни к
    чему, но последствие названо одно на всех и одной строкой. Обход сверяет
    имя папки со списком (`scanner._walk_managed`), и пустой список не
    пропускает никого: «Переразложить старое» дальше корня загрузок не идёт —
    галочка стоит, план строится, старые загрузки в нём не участвуют, — а
    уборка опустевших папок (`mover._cleanup_emptied`) не убирает ничего, и
    после отката в загрузках остаётся весь каркас из пустых папок. Снаружи это
    неотличимо от прибранной папки.

    Дорога сюда короткая и молчаливая: `managed_folders` в правилах просто нет.
    Раздел не того типа или из одних пробелов разбор называет своими словами
    (`_text_list`, `_trim_managed`), а забытый ключ до этой правки не говорил
    ничего вовсе — тот самый третий вход валидатора, про который забывают:
    правильный, испорченный и отсутствующий.
    """
    if not managed:
        problems.append(
            f"{where}: managed_folders пуст — своей программа не считает ни "
            "одну папку. «Переразложить старое» дальше корня загрузок не "
            "пойдёт, и опустевшие папки останутся лежать.")
        return
    known = folder_keys(managed)
    seen: set[str] = set()
    for kind, verb, names in (("категория", "указана", categories),
                              ("тип", "указан", types)):
        for name in names:
            for part in _SEPARATORS.split(name):
                key = folder_key(part)
                if not part or key in known or key in seen:
                    continue
                seen.add(key)
                problems.append(
                    f"{where}: {kind} «{part}» не {verb} в managed_folders. "
                    "Файлы в неё разложатся, но «Переразложить старое» в эту "
                    "папку больше не зайдёт и пустой её не уберёт.")


def _check_type_map(
    type_map: dict[str, list[str]], where: str, problems: list[str]
) -> None:
    """Жалуется на расширение, названное сразу в двух типах.

    `match_type` отдаёт первый подошедший тип, значит вторая запись не работает
    никогда. Снаружи она выглядит как обычное правило: строка в файле есть,
    ошибок нет, а файл ложится в другую подпапку — и понять, почему `.exr`
    оказался в `Images`, если в `type_map["3D"]` он тоже написан, можно только
    зная про этот порядок. Ровно тот же случай, что у битой регулярки: запись
    похожа на рабочее правило, но правилом не является, и молчание тут хуже
    жалобы. В поставляемых правилах такая запись и нашлась.

    Сверяемся так же, как `match_type` (`extension_key`): `"PDF"`, `"pdf"` и
    `".pdf"` — одно расширение, и написать их в разных типах так же легко. Пока
    сверка шла строка в строку, пара `".pdf"`/`"pdf"` призраком не считалась —
    то есть проверка молчала ровно там, где написание и разошлось.
    """
    seen: dict[str, str] = {}
    for type_name, extensions in type_map.items():
        for value in extensions:
            key = extension_key(value)
            if key in seen:
                if seen[key] != type_name:
                    problems.append(
                        f"{where}: расширение «{value}» названо и в типе "
                        f"«{seen[key]}», и в «{type_name}». Работает только "
                        f"первый — «{seen[key]}».")
            else:
                seen[key] = type_name


@dataclass
class Config:
    downloads_path: str
    categories: dict[str, list[str]] = field(default_factory=dict)
    patterns: dict[str, list[str]] = field(default_factory=dict)
    category_hints: dict[str, str] = field(default_factory=dict)
    type_map: dict[str, list[str]] = field(default_factory=dict)
    managed_folders: list[str] = field(default_factory=list)
    ignore: list[str] = field(default_factory=list)
    overrides: dict[str, str] = field(default_factory=dict)
    external_3d: dict = field(default_factory=dict)
    fallback_category: str = "Others"
    fallback_type: str = "Misc"
    extra: dict = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)
    # `overrides.json` рядом лежит, но разобрать его не вышло.
    #
    # Отличать это от «файла нет» приходится потому, что писать в него умеет
    # окно (кнопка «✨ИИ»), а пустой словарь у обоих случаев одинаковый. Файла
    # нет — писать можно, терять нечего. Файл есть и не читается — там могут
    # лежать сотни решений, принятых руками, и запись на его место стёрла бы
    # их все разом (см. `ui_qt._save_overrides`).
    overrides_unreadable: bool = False
    # Записи `overrides.json`, которые разбор отверг: непригодная категория,
    # правило в запасную папку, значение не строкой.
    #
    # Держим их отдельно по той же причине, по какой `extra` держит незнакомые
    # ключи `config.json`: работать с ними нельзя, а выбросить — значит стереть
    # строку, которую писали руками. Разбор про такую запись говорит
    # «Пропущено», человек слышит «в этот раз не применилось» и собирается
    # починить опечатку в редакторе, — а первое же нажатие «✨ИИ» записывало на
    # место файла то, что осталось в памяти, и чинить становилось нечего
    # (см. `ui_qt._save_overrides`).
    overrides_dropped: dict[str, str] = field(default_factory=dict)
    # `config.json` рядом лежит, но разобрать его не вышло. Случай тот же, что
    # и у `overrides.json`, и ответ тот же: на место нечитаемого файла не пишем
    # (см. `save`).
    settings_unreadable: bool = False

    @classmethod
    def load(cls, path: str | Path) -> "Config":
        """Читает настройки из `path` и правила из `rules.json` рядом.

        Если `rules.json` нет — это конфиг старой версии, где правила лежали
        вместе с настройками. Тогда берём их оттуда, чтобы программа не
        осталась вовсе без категорий.

        Испорченный файл не мешает запуску: о нём пишем в `problems`, а
        работаем с тем, что есть. Это касается и самого `config.json` — его
        программа переписывает при каждом закрытии окна, и оборванная запись
        (нет места, выключили питание) не должна превращать её в кирпич со
        стеком вместо окна. Кирпич хуже вдвойне: поправить путь через интерфейс
        уже не выйдет, потому что интерфейс не открывается.
        """
        path = Path(path)
        problems: list[str] = []
        data = _read_json(path, problems)
        # Файл есть, а разобрать его не вышло. Дальше работаем с пустым
        # словарём, как и раньше, но запись на это место закрываем: там лежит
        # настроенный путь к загрузкам и путь к папке 3D, а взять их больше
        # неоткуда. Сказать об этом надо при старте — на закрытии окна говорить
        # уже некому и некуда.
        settings_unreadable = data is None and path.exists()
        if settings_unreadable:
            problems.append(
                f"{path.name}: пока файл не починят, окно не будет писать в "
                "него настройки — иначе то, что в нём лежит, заменится на "
                "пустое. Поправь его в редакторе или удали, и программа "
                "создаст новый.")
        data = data or {}

        # Пробелы по краям пути срезаем: поле окна делает это давно, а правку
        # руками (копипаст из письма, зацепленный при редактировании пробел)
        # никто не подчищал. Хвостовой пробел на Windows коварнее всего:
        # `is_dir()` его отрезает и отвечает «папка на месте», а обход такой
        # папки не возвращает ничего — наружу это выходит как «План готов:
        # 0 шт.», то есть неотличимо от уже прибранных загрузок.
        downloads = data.get("downloads_path")
        if isinstance(downloads, str):
            downloads = downloads.strip()
        if not isinstance(downloads, str) or not downloads:
            problems.append(
                "config.json: папка загрузок не указана. "
                f"Взята папка по умолчанию: {DEFAULT_DOWNLOADS}")
            downloads = DEFAULT_DOWNLOADS

        rules_path = path.with_name(RULES_FILENAME)
        rules = _read_json(rules_path, problems) if rules_path.exists() else None
        # Правила лежат в самом config.json — старая установка. Тогда они и есть
        # незнакомые ключи: выбросить их при сохранении значит стереть
        # единственную копию, взять её обратно неоткуда.
        inline_rules = rules is None
        if rules is None:
            rules = data

        rules_name = path.name if inline_rules else RULES_FILENAME
        overrides_name = path.with_name(OVERRIDES_FILENAME).name
        skip = USER_KEYS if inline_rules else RULE_KEYS + USER_KEYS

        # Разделы разбираются по порядку: жалобы в `problems` должны идти в том
        # же порядке, в каком они лежат в файле, — так их проще искать глазами.
        categories = _rule_map(rules.get("categories"), rules_name, "categories", problems)
        patterns = _pattern_map(rules.get("patterns"), rules_name, "patterns", problems)
        category_hints = _text_map(
            rules.get("category_hints"), rules_name, "category_hints", problems)
        type_map = _rule_map(rules.get("type_map"), rules_name, "type_map", problems)
        managed_folders = _trim_managed(
            _text_list(rules.get("managed_folders"), rules_name,
                       "managed_folders", problems),
            rules_name, problems)
        ignore = _text_list(rules.get("ignore"), rules_name, "ignore", problems)
        # Пустой словарь получается и когда файла нет, и когда он есть, но не
        # читается. Для работы это одно и то же, а для записи — нет: во втором
        # случае на диске лежат правила, которых мы не знаем.
        overrides_path = path.with_name(OVERRIDES_FILENAME)
        raw_overrides = _read_json(overrides_path, problems)
        overrides_unreadable = raw_overrides is None and overrides_path.exists()
        overrides = _text_map(
            raw_overrides, overrides_name, "правила", problems, folders=True)
        external_3d = _clean_3d(data.get("external_3d"), problems)
        fallback_category = _text(
            rules.get("fallback_category"), "Others",
            rules_name, "fallback_category", problems)
        fallback_type = _text(
            rules.get("fallback_type"), "Misc", rules_name, "fallback_type", problems)

        # Ручное правило «в запасную категорию» — замороженное «не знаю». Знать
        # имя запасной папки для этого надо, поэтому проверка идёт после разбора
        # правил, а не внутри него.
        overrides = _drop_frozen_rules(
            overrides, fallback_category, overrides_name, problems)

        # Что из файла не доехало до `overrides`. Работать с этим нельзя, а
        # стирать — тем более: строку писали руками, второй копии у неё нет.
        overrides_dropped = {
            name: value for name, value in (raw_overrides or {}).items()
            if name not in overrides}

        # Раскладывать не по чему. Снаружи это выглядит как обычная работа:
        # план построен, файлы разложены, жалоб нет — только все до одного
        # уехали в запасную папку, и отличить это от честно неопознанных
        # загрузок нельзя ничем.
        #
        # Дорога сюда короткая: `rules.json` лежит рядом с программой отдельным
        # файлом, и пропасть ему просто — из архива скопировали один `.exe`,
        # антивирус унёс файл в карантин, установку перенесли наполовину. Тогда
        # `Config` считает конфиг старым (правила раньше лежали в config.json) и
        # молча берёт правила оттуда, где их нет. Пустой при этом и
        # `managed_folders`, то есть «Переразложить старое» в запасную папку не
        # зайдёт и разгрести не поможет, пока файл правил не вернётся на место.
        #
        # Раскладка на одних шаблонах или одних ручных правилах — настройка
        # рабочая, поэтому жалуемся, только когда пусто везде.
        if not categories and not patterns and not overrides:
            missing = ("" if rules_path.exists()
                       else f" Файла {RULES_FILENAME} рядом с настройками нет.")
            problems.append(
                "Правил раскладки нет ни одного: ни категорий, ни шаблонов, ни "
                f"ручных правил. Все файлы уедут в «{fallback_category}»."
                + missing)

        # Расширение, названное в двух типах, работает только в первом. Вторая
        # запись — правило-призрак: на вид рабочая, на деле мёртвая.
        _check_type_map(type_map, rules_name, problems)

        # Папку создаёт любая категория, откуда бы она ни пришла: из правил, из
        # шаблона, из ручной записи в overrides.json или из запасной строки.
        _check_managed(
            [*categories, *patterns, *overrides.values(), fallback_category],
            [*type_map, fallback_type],
            managed_folders, rules_name, problems)

        return cls(
            downloads_path=downloads,
            categories=categories,
            patterns=patterns,
            category_hints=category_hints,
            type_map=type_map,
            managed_folders=managed_folders,
            ignore=ignore,
            overrides=overrides,
            external_3d=external_3d,
            fallback_category=fallback_category,
            fallback_type=fallback_type,
            extra={k: v for k, v in data.items() if k not in skip},
            problems=problems,
            overrides_unreadable=overrides_unreadable,
            overrides_dropped=overrides_dropped,
            settings_unreadable=settings_unreadable,
        )

    def save(self, path: str | Path) -> None:
        """Пишет только настройки пользователя. Правила не трогает.

        Файл, который не удалось прочитать при запуске, не переписываем вовсе —
        то же правило, что и у `overrides.json`. Дорога сюда короткая: человек
        правит `config.json` руками (README про него рассказывает), забывает
        скобку, запускает программу. Разбор говорит «не читается», подставляет
        `~/Downloads` и работает дальше; человек закрывает окно — и на место
        файла ложится свежий, с папкой по умолчанию. Настроенный путь, путь к
        папке 3D и сам текст с опечаткой, который чинился в редакторе за
        минуту, исчезают разом, и взять их неоткуда.

        Что окно теперь молчит про настройки, сказано при старте, вместе с
        жалобой на сам файл: на закрытии говорить уже некому и некуда.

        Незнакомые ключи из файла возвращаются на место: если кто-то дописал
        своё в config.json, сохранение из окна не должно это стирать.

        Список расширений 3D дописывается сам: окно про него не знает и знать не
        должно, а без него настройка выглядит рабочей, но не делает ничего.

        В конце файла — перевод строки. Без него закрытие окна каждый раз
        превращало config.json в изменённый файл: содержимое то же, а `git diff`
        показывает «\\ No newline at end of file». В репозитории программы это
        шум при каждом запуске, а редакторы и консольные утилиты последнюю
        строку без перевода показывают склеенной со следующей.
        """
        if self.settings_unreadable:
            return
        data = {
            **self.extra,
            "downloads_path": self.downloads_path,
            "external_3d": _clean_3d(self.external_3d, []) if self.external_3d else {},
        }
        Path(path).write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
