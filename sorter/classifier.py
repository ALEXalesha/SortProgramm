"""Классификация файла: (категория, тип, расширение)."""
from __future__ import annotations

import re

from .config import Config, extension_key, name_key


# Служебный номер, который программа приписывает при конфликте имён:
# `отчёт.pdf` -> `отчёт (1).pdf`.
_DEDUP_SUFFIX = re.compile(r"\s*\(\d+\)$")

# Пометки причин для предпросмотра. `BY_CONTENT` отделён от `BY_WORD` нарочно:
# слово, найденное внутри текстового файла, глазами не проверить — в имени его
# нет. Это единственная причина, которую нельзя перепроверить, глядя на строку
# плана, поэтому она и названа отдельно.
BY_RULE = "правило"
BY_PATTERN = "шаблон"
BY_WORD = "слово"
BY_CONTENT = "слово в файле"
UNKNOWN = "не опознан"


def base_name(filename: str) -> str:
    """Имя без служебного номера ` (1)`, приписанного разрешением конфликтов.

    Номер вставляется перед расширением, то есть ровно туда, где кончается
    смысловая часть имени. Слова вроде `-fon.` или `.exe` из-за этого перестают
    совпадать, и переразложение уносит уже разложенный файл в Others — просто
    потому, что программа сама его когда-то переименовала.

    Регулярки в rules.json обходят это вручную, дописывая `(\\s*\\(\\d+\\))?`
    к каждому шаблону. Здесь то же самое делается один раз и для слов тоже.
    """
    stem, dot, extension = filename.rpartition(".")
    if not dot:
        return _DEDUP_SUFFIX.sub("", filename)
    return _DEDUP_SUFFIX.sub("", stem) + dot + extension


def find_override(overrides: dict[str, str], filename: str) -> str | None:
    """Ручное правило для имени файла. None, если правила нет.

    Ищется в четыре захода: точное имя, имя без служебного номера, и то же
    самое по правилам файловой системы (`name_key`). Точное совпадение всегда
    важнее — если в файле лежат две записи, срабатывает та, что написана как
    сам файл.

    Регистр приходится смягчать по той же причине, по какой его смягчили для
    папок: на Windows `Отчёт.pdf` и `отчёт.pdf` — один и тот же файл, а сверка
    шла строка в строку. Ручное правило пишут руками, глядя на имя в
    проводнике, а проводник показывает его как хочет — с заглавной, целиком
    капсом после переименования из другой программы, — и ключ, набранный не тем
    регистром, не совпадал ни с чем. Правило при этом выглядит совершенно
    рабочим: строка в `overrides.json` есть, ошибок нет, а файл молча уезжает
    по ключевым словам или в `Others`, и в предпросмотре у него честная пометка
    «слово». Отличить это от «правила и не было» нельзя ничем.

    На Linux и macOS `name_key` ничего не меняет: там это и правда разные
    файлы, и путать их было бы уже вторжением в чужое.

    Заходов именно четыре, а не три: раньше оба захода по правилам файловой
    системы были свалены в один проход по словарю с общим набором искомых имён,
    и решал не порядок заходов, а порядок строк в `overrides.json`. Правило,
    написанное ровно под `отчёт (1).pdf`, но не тем регистром, проигрывало
    правилу для `отчёт.pdf`, если стояло ниже, — и та же пара правил,
    переставленная местами, отправляла файл в другую категорию. Правило под
    номерное имя пишут нарочно: `отчёт (1).pdf` — это второй отчёт, и место у
    него своё.

    Перебор по всему словарю нестрашен: он случается только когда точного
    совпадения нет, а правил в `overrides.json` сотни, не миллионы.
    """
    stripped = base_name(filename)
    for key in (filename, stripped):
        value = overrides.get(key)
        if value:
            return value
    for wanted in (name_key(filename), name_key(stripped)):
        for key, value in overrides.items():
            if value and name_key(key) == wanted:
                return value
    return None


def extension_of(filename: str) -> str:
    """Расширение в нижнем регистре без точки. Пустая строка, если его нет."""
    name = filename.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
    if "." not in name.strip("."):
        return ""
    return name.rsplit(".", 1)[-1].lower()


def match_type(extension: str, type_map: dict[str, list[str]], fallback: str = "Misc") -> str:
    """Тип файла по карте расширение→тип. Иначе fallback.

    Ни регистр, ни точка, ни пробелы по краям не важны с обеих сторон
    (`extension_key`). Карту типов README предлагает править руками, и
    `"Documents": ["PDF"]` там появляется само собой — а сравнение шло с
    приведённым к нижнему регистру расширением против списка как есть.
    Совпадений не было, и все документы молча уезжали в `Misc`: раскладка
    неверная, жалоб никаких.

    Регистр починили, а точку — нет, хотя приходит она тем же путём и тем же
    исходом: в одном проекте живут три написания одного и того же (слова
    категорий с точкой, `type_map` без, `external_3d.extensions` без), и
    `".pdf"`, написанное здесь, не совпадало с `"pdf"` ни разу. Список выноса
    3D это прощает давно — теперь и карта типов.

    Пустой ключ не совпадает ни с чем нарочно. У файла без расширения
    `extension_of` отдаёт пустую строку, и запись `""` (или из одних пробелов,
    или одна точка) выдавала бы таким файлам настоящий тип вместо запасного.
    Разбор правил такую запись выбрасывает, но конфиг собирают и напрямую — из
    тестов, из CLI, — и проверять там некому.
    """
    ext = extension_key(extension)
    if not ext:
        return fallback
    for type_name, extensions in type_map.items():
        if any(ext == extension_key(e) for e in extensions):
            return type_name
    return fallback


def _in_text(word: str, text: str) -> bool:
    """Есть ли ключевое слово в содержимом файла — с границами слова.

    В имени файла подстрока — это приём: `задач` ловит и `задачи`, и
    `задачник`, а имя короткое, и лишнего в нём почти не бывает. В тексте на
    две тысячи знаков тот же приём превращается в лотерею. `obs` (OBS Studio)
    находится в «observed» и «problems», `demo` (демоверсия) — в
    «demonstrating» и «democracy», и заметка про ИИ уезжает в «Программы».
    Проверить это нечем: пометка «слово в файле» именно тем и отличается от
    остальных, что искомого слова в имени нет, и глазами по строке плана
    ничего не увидеть.

    Поэтому в тексте слово требует границы. Спереди — всегда, если само слово
    начинается с буквы. Сзади — только если оно кончается латинской буквой:
    латиница в этих правилах это названия целиком (`obs`, `node`, `epic`,
    `zoom`), а кириллица написана основами нарочно, потому что склоняется —
    `решени` обязано ловить «решения». Слово, у которого край и так не буква
    (`-fon.`, `счёт-`, `pla0`), границу несёт в себе, и требовать вторую
    значило бы запретить его вовсе.
    """
    head = r"(?<![^\W\d_])" if word[:1].isalpha() else ""
    last = word[-1:]
    tail = r"(?![^\W\d_])" if last.isalpha() and last.isascii() else ""
    return re.search(head + re.escape(word) + tail, text) is not None


def find_category(
    filename: str, content: str, categories: dict[str, list[str]]
) -> tuple[str, bool] | None:
    """Категория и где нашлось слово: True — в имени, False — в содержимом.

    Сначала ищем слово в имени файла, затем в содержимом. Сравнение —
    регистронезависимое вхождение подстроки. None, если ничего не подошло.

    Слова, начинающиеся с точки (`.exe`, `.json`, `.gguf`), — это расширения, и
    по содержимому они не ищутся. Иначе заметка со строкой «скачай installer.exe»
    объявлялась бы программой: в тексте такие подстроки встречаются сплошь и
    рядом, а значат совсем не то, что в имени файла.

    Откуда пришло слово, знать надо снаружи: в предпросмотре у этих двух случаев
    разные пометки. Совпадение по содержимому глазами не проверить — в имени
    искомого слова нет.

    В имени слово ищется подстрокой, в содержимом — с границами слова
    (`_in_text`): в коротком имени лишнее попадается редко, в длинном тексте —
    постоянно.

    Пустое слово — и слово из одних пробелов — не совпадает ни с чем нарочно.
    Подстрокой оно входит в любое имя, то есть первая же категория с такой
    записью забирает себе всю папку загрузок, и отличить это от исправной
    работы нельзя ничем: план построен, файлы разложены, в предпросмотре у
    каждой строки честная пометка «слово». Разбор правил такую запись
    выбрасывает с жалобой, но конфиг собирают и напрямую — из тестов, из
    CLI, — и там проверять некому. `match_type` закрылся от пустого расширения
    ровно по этой причине; поиск по словам, который решает не тип, а категорию,
    оставался открытым. Пробелы ВНУТРИ слова не трогаем: `" фон "` — это приём,
    способ потребовать границы слова.

    >>> Это сердце логики. Порядок категорий в config задаёт приоритет:
    первая подошедшая выигрывает. Хочешь иначе (по границам слова,
    вес имени против содержимого) — менять здесь.
    """
    name = filename.lower()
    body = content.lower()
    for source, in_name in ((name, True), (body, False)):
        for category, keywords in categories.items():
            for word in keywords:
                word = word.lower()
                if not word.strip():
                    continue
                if in_name:
                    if word in source:
                        return category, True
                elif not word.startswith(".") and _in_text(word, source):
                    return category, False
    return None


def match_category(filename: str, content: str, categories: dict[str, list[str]]) -> str | None:
    """Категория по ключевым словам. None, если ничего не подошло."""
    found = find_category(filename, content, categories)
    return found[0] if found else None


def match_pattern(filename: str, patterns: dict[str, list[str]]) -> str | None:
    """Категория по регулярному выражению на имени файла. None, если не подошло.

    Точнее ключевых слов: ловит то, что подстрокой не выразить. Например
    рендеры Blender называются диапазоном кадров (`0001-0250.mp4`), а скриншоты —
    датой (`Снимок экрана 2026-05-28 185311.png`). Ни то, ни другое не описать
    словом-подстрокой, не задев кучу лишнего.

    Битое выражение тихо пропускаем: опечатка в config.json не должна ронять
    сортировку целиком.
    """
    for category, expressions in patterns.items():
        for expression in expressions:
            try:
                if re.search(expression, filename, re.IGNORECASE):
                    return category
            except re.error:
                continue
    return None


def explain_category(filename: str, content: str, config: Config) -> tuple[str, str]:
    """Категория и чем она выбрана: (категория, причина).

    Приоритет: overrides → регулярки → ключевые слова → fallback. Регулярки
    идут раньше слов, потому что они конкретнее: `0001-0250.mp4` — точно
    рендер, а слово «mp4» в списке Медиа забрало бы его себе.

    Причина нужна для предпросмотра. Когда переразложение двигает сотню уже
    разложенных файлов, «почему» важнее «куда»: по нему видно, сработало
    новое правило или старая запись в overrides.

    Разбирается имя без служебного номера (`base_name`), чтобы файл, который
    программа сама переименовала в `отчёт (1).pdf`, оставался тем же файлом.
    Правило под точное имя всё-таки ищется первым: если руки написали его
    именно для `отчёт (1).pdf`, значит так и хотели.

    Слово, найденное внутри файла, называется отдельной пометкой. Содержимое
    читается у `txt`, `md` и `csv`, и совпадение по нему неотличимо от
    совпадения по имени: `README.md` уезжает в «Учёбу» с пометкой «слово», а
    слова «Учёбы» в имени нет ни одного — искать его там бесполезно, оно в
    тексте. README советует просматривать в плане именно строки «слово», то
    есть непроверяемой оказывалась ровно та пометка, на которую велено
    смотреть. Тот же случай, что у выноса 3D: причина названа, но не та.
    """
    name = base_name(filename)
    override = find_override(config.overrides, filename)
    if override:
        return override, BY_RULE

    by_pattern = match_pattern(name, config.patterns)
    if by_pattern:
        return by_pattern, BY_PATTERN

    by_word = find_category(name, content, config.categories)
    if by_word:
        category, in_name = by_word
        return category, BY_WORD if in_name else BY_CONTENT

    return config.fallback_category, UNKNOWN


def classify(filename: str, content: str, config: Config) -> tuple[str, str, str]:
    """Возвращает тройку (категория, тип, расширение)."""
    category, _ = explain_category(filename, content, config)
    extension = extension_of(filename)
    file_type = match_type(extension, config.type_map, config.fallback_type)
    return category, file_type, extension
