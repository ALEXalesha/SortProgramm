"""Мелкие общие помощники."""
from __future__ import annotations

import codecs
from pathlib import Path

# Сколько строк показываем, прежде чем свернуть хвост. Окно не резиновое, а на
# сотне ошибок список всё равно не читают — важно, что они есть и какие первые.
REPORT_LIMIT = 10

# Метки, с которых начинается файл в UTF-16. Определять эту кодировку иначе
# нельзя: почти любая чётная строка байтов «раскодируется» как UTF-16 без
# ошибки, поэтому пробовать её вслепую значит объявить текстом набор иероглифов.
_UTF16_MARKS = (b"\xff\xfe", b"\xfe\xff")


def decode_text(raw: bytes) -> str:
    """Байты словами. Не разобралось ничем — пустая строка.

    Один читатель на всё, что в этой программе набирают руками: содержимое
    `.txt`/`.md`/`.csv`, из которого берутся ключевые слова, и три файла
    настроек — `config.json`, `rules.json`, `overrides.json`. README предлагает
    править их в редакторе, а «редактор» на Windows — это Блокнот, PowerShell и
    всё, что осталось с прошлых лет. Блокнот предлагает сохранить «в UTF-8 с
    BOM», «в UTF-16 LE» и «в ANSI», `Out-File` в PowerShell 5.1 пишет UTF-16 по
    умолчанию, а Excel отдаёт `.csv` в cp1251.

    Каждый такой файл читался ровно одним способом и по-своему. Ключ DeepSeek
    научился читаться во всех трёх кодировках после того, как UTF-16 из
    Блокнота гасил окно; содержимое текстовых файлов — после того, как cp1251
    съедал слова целиком. Настройки оставались последними, кто знал одну
    кодировку: BOM для `json` не пробел, а неожиданный символ, и файл с ним
    объявлялся нечитаемым. Исход у правил худший из возможных — их нет ни
    одного, и вся папка загрузок уезжает в `Others`; у настроек — путь к
    загрузкам подменяется папкой по умолчанию.

    Обрыв куска на середине символа поломкой не считается: неполный хвост
    держит у себя пошаговый декодер. Без этого обрезанный по границе байтов
    UTF-8 объявлялся бы битым и уезжал разбираться как cp1251 целиком.
    """
    encodings = ("utf-16",) if raw[:2] in _UTF16_MARKS else ("utf-8-sig", "cp1251")
    for encoding in encodings:
        try:
            return codecs.getincrementaldecoder(encoding)().decode(raw)
        except UnicodeDecodeError:
            continue
    return ""


def read_text(path: Path) -> str:
    """Файл словами, в какой бы кодировке его ни сохранили (`decode_text`)."""
    return decode_text(Path(path).read_bytes())


def rel_to(path: Path, root: Path) -> str:
    """Путь относительно корня; абсолютный, если он вне корня (напр. All_3d)."""
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def listing(pairs: list[tuple[str, str]], limit: int | None = REPORT_LIMIT) -> str:
    """Пары «что → почему» списком. Длинный хвост сворачивается.

    `limit=None` — не сворачивать. Хвост режется ради окна, которое не
    резиновое; в консоли резать нечего — там список листают.
    """
    shown = pairs if limit is None else pairs[:limit]
    lines = "\n".join(f"• {what}: {why}" for what, why in shown)
    tail = f"\n…и ещё {len(pairs) - len(shown)}" if len(pairs) > len(shown) else ""
    return lines + tail


def report(result, limit: int | None = REPORT_LIMIT) -> str:
    """Итог применения плана словами: сколько переехало, что нет и почему.

    Ошибки надо называть поимённо. Раньше окно показывало только их число —
    «Перемещено: 7, ошибок: 3», — и на этом разговор заканчивался: какие три
    файла, что с ними случилось, повторять ли попытку, узнать было неоткуда.
    А между «Очистить» и «Применить» проходит сколько угодно времени, и причины
    самые обычные: файл открыт другой программой, его успели переименовать или
    удалить, кончилось место. Такой файл остаётся лежать в загрузках, и человек
    должен знать, о ком речь. CLI печатает эти строки давно — окна молчали.

    Оговорки («лёг под другим именем») показывались и раньше: план обещал одно,
    а вышло другое, и молча расходиться с тем, что человек только что прочитал
    в таблице, нельзя. Теперь обе половины отчёта собираются в одном месте,
    чтобы Qt, Tkinter и консоль говорили одно и то же.

    Пропавший журнал отмены назван отдельной строкой. Раньше он лежал в общем
    списке неудач и печатался под заголовком «Не переехали» — при том, что
    переехали все до одного файла, а «журнал отмены» и не файл вовсе. Само
    последствие при этом терялось среди чужих строк, а оно тут единственное и
    вполне определённое: файлы разложены, но вернуть их назад больше нечем —
    «🕘 История» об этой сортировке не знает.
    """
    parts = [f"Перемещено: {result.moved}, ошибок: {len(result.errors)}"]
    if result.errors:
        parts.append("Не переехали:\n" + listing(result.errors, limit))
    if result.notes:
        parts.append("Легли под другим именем:\n" + listing(result.notes, limit))
    if result.undo_failed:
        parts.append(
            "Отменить эту сортировку не выйдет: журнал отмены не записан "
            f"({result.undo_failed}).")
    return "\n\n".join(parts)
