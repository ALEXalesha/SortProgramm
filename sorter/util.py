"""Мелкие общие помощники."""
from __future__ import annotations

import codecs
from pathlib import Path

# Сколько строк показываем, прежде чем свернуть хвост. Окно не резиновое, а на
# сотне ошибок список всё равно не читают — важно, что они есть и какие первые.
REPORT_LIMIT = 10

# Заголовки того, что разбор настроек говорит при старте. Одни на три
# интерфейса: набранный во второй раз заголовок однажды разойдётся с остальными,
# и проверка правил через консоль перестанет проверять окно.
SETTINGS_ALARM = "Настройки прочитаны не полностью"
SETTINGS_NOTICE = "Правила подчищены при чтении"

# Метки, с которых начинается файл в UTF-16. Определять эту кодировку иначе
# нельзя: почти любая чётная строка байтов «раскодируется» как UTF-16 без
# ошибки, поэтому пробовать её вслепую значит объявить текстом набор иероглифов.
_UTF16_MARKS = (b"\xff\xfe", b"\xfe\xff")


def decode_text(raw: bytes) -> str:
    """Байты словами. Не разобралось ничем — пустая строка.

    Один читатель на всё, что в этой программе набирают руками: содержимое
    `.txt`/`.md`/`.csv`, из которого берутся ключевые слова, и три файла
    настроек — `config.json`, `rules.json`, `overrides.json`. README предлагает
    править их в редакторе, а «редактор» на Windows — это Блокнот, PowerShell и
    всё, что осталось с прошлых лет. Блокнот предлагает сохранить «в UTF-8 с
    BOM», «в UTF-16 LE» и «в ANSI», `Out-File` в PowerShell 5.1 пишет UTF-16 по
    умолчанию, а Excel отдаёт `.csv` в cp1251.

    Каждый такой файл читался ровно одним способом и по-своему. Содержимое
    текстовых файлов научилось читаться во всех трёх кодировках после того, как
    cp1251 съедал слова целиком. Настройки оставались последними, кто знал одну
    кодировку: BOM для `json` не пробел, а неожиданный символ, и файл с ним
    объявлялся нечитаемым. Исход у правил худший из возможных — их нет ни
    одного, и вся папка загрузок уезжает в `Others`; у настроек — путь к
    загрузкам подменяется папкой по умолчанию.

    Обрыв куска на середине символа поломкой не считается: неполный хвост
    держит у себя пошаговый декодер. Без этого обрезанный по границе байтов
    UTF-8 объявлялся бы битым и уезжал разбираться как cp1251 целиком.
    """
    encodings = ("utf-16",) if raw[:2] in _UTF16_MARKS else ("utf-8-sig", "cp1251")
    for encoding in encodings:
        try:
            return codecs.getincrementaldecoder(encoding)().decode(raw)
        except UnicodeDecodeError:
            continue
    return ""


def read_text(path: Path) -> str:
    """Файл словами, в какой бы кодировке его ни сохранили (`decode_text`)."""
    return decode_text(Path(path).read_bytes())


def rel_to(path: Path, root: Path) -> str:
    """Путь относительно корня; абсолютный, если он вне корня (напр. All_3d)."""
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def listing(pairs: list[tuple[str, str]], limit: int | None = REPORT_LIMIT) -> str:
    """Пары «что → почему» списком. Длинный хвост сворачивается.

    `limit=None` — не сворачивать. Хвост режется ради окна, которое не
    резиновое; в консоли резать нечего — там список листают.
    """
    shown = pairs if limit is None else pairs[:limit]
    lines = "\n".join(f"• {what}: {why}" for what, why in shown)
    tail = f"\n…и ещё {len(pairs) - len(shown)}" if len(pairs) > len(shown) else ""
    return lines + tail


def settings_message(
    problems: list[str], notices: list[str]
) -> tuple[str, str, bool]:
    """Что сказать про разбор настроек: заголовок, текст и «поломка ли это».

    Разбор отвечает двумя списками, и разница между ними для человека
    решающая. `problems` — беда: файл прочитан не целиком, раздел выброшен,
    правило не применилось. Идти чинить надо сейчас, потому что раскладка
    получится не та. `notices` — наоборот: файл прочитан целиком, строку
    выбросили нарочно, и раскладка от этого стала ВЕРНЕЕ.

    Долгое время оба списка были одним, и на общий печатались слова про
    первый: «Настройки прочитаны не полностью», «раскладка может быть
    неверной». Для правила «в запасную категорию» (`config._drop_frozen_rules`)
    обе фразы ложны, а показывалось оно при каждом запуске навсегда — строки
    нарочно остаются в файле. Исходов у такого сообщения два, и оба плохие:
    человек идёт искать поломку, которой нет, или перестаёт читать этот список
    вовсе — вместе с настоящими поломками, стоящими там же.

    Уведомление не теряется и рядом с поломкой: строки в файле остались, и
    убрать их всё ещё стоит. Меняется только заголовок — по нему решают,
    бросать ли дела.
    """
    blocks = []
    if problems:
        blocks.append("\n".join(f"• {p}" for p in problems))
    if notices:
        lead = ("Заодно пропущены строки, которые ничего не решают:\n"
                if problems else "")
        blocks.append(lead + "\n".join(f"• {n}" for n in notices))
    if problems:
        blocks.append("Программа запустилась, но раскладка может быть неверной.")
        return SETTINGS_ALARM, "\n\n".join(blocks), True
    blocks.append("Файлы разложатся правильно и без этих строк. "
                  "Убери их из файла, чтобы сообщение больше не появлялось.")
    return SETTINGS_NOTICE, "\n\n".join(blocks), False


# Почему «Применить» ничего не двигает. Пустой список перемещений получается
# тремя разными путями, и совет у каждого свой (см. `nothing_to_apply`).
PLAN_NOT_BUILT = "не строили"
PLAN_NO_FOLDER = "нет папки"
PLAN_EMPTY = "пусто"


def nothing_to_apply(state: str) -> tuple[str, str]:
    """Заголовок и текст для «Применить», когда двигать нечего.

    Состояний три, а ответ до сих пор был один — «Нет плана. Сначала нажми
    «Очистить»», — и в двух случаях из трёх он неверен.

    Ненайденная папка: окно в ту же секунду пишет «Папка не найдена», а кнопка
    советует нажать «Очистить», после чего окно скажет ровно то же самое.
    Совет замыкает круг, из которого им же и не выйти, а причина — отключённый
    диск, переименованная папка, опечатка в пути — не названа ни словом.

    Прибранная папка: план построен, в нём честный ноль, и «Очистить» даст тот
    же ноль. Здесь совет тише, но ведёт по тому же кругу — и умалчивает про
    «Переразложить старое», единственную кнопку, которая в этом состоянии ещё
    что-то меняет.

    Разницу окно знает точно: `preview` только что прошёл по одной из трёх
    веток. Терялась она между двумя нажатиями, потому что наружу выходил один
    лишь пустой список.
    """
    if state == PLAN_NO_FOLDER:
        return ("Папка не найдена",
                "Папки, которую показывает окно, на диске нет — двигать нечего.\n\n"
                "Проверь путь: диск мог отключиться, флешку вынуть, а папку "
                "переименовать или удалить.")
    if state == PLAN_EMPTY:
        return ("Двигать нечего",
                "План построен, и в нём ни одной строки: всё уже лежит по своим "
                "папкам.\n\nЕсли ждал другого — включи «Переразложить старое». "
                "Тогда проверятся заново и файлы, разложенные раньше.")
    return ("Нет плана", "Сначала нажми «Очистить».")


def report_title(result) -> str:
    """Заголовок отчёта: гладко всё прошло или с оговорками.

    Текст отчёта общий на три интерфейса давно (`report`), а заголовок каждое
    окно ставило своё: Tkinter отличал «Готово с оговорками», PyQt показывал
    тревожный значок под словом «Готово». Значок из окна уходит вместе с
    окном, а заголовок остаётся в списке уведомлений Windows.
    """
    return ("Готово с оговорками"
            if result.errors or result.notes or result.undo_failed else "Готово")


def report(result, limit: int | None = REPORT_LIMIT) -> str:
    """Итог применения плана словами: сколько переехало, что нет и почему.

    Ошибки надо называть поимённо. Раньше окно показывало только их число —
    «Перемещено: 7, ошибок: 3», — и на этом разговор заканчивался: какие три
    файла, что с ними случилось, повторять ли попытку, узнать было неоткуда.
    А между «Очистить» и «Применить» проходит сколько угодно времени, и причины
    самые обычные: файл открыт другой программой, его успели переименовать или
    удалить, кончилось место. Такой файл остаётся лежать в загрузках, и человек
    должен знать, о ком речь. CLI печатает эти строки давно — окна молчали.

    Оговорки («лёг под другим именем») показывались и раньше: план обещал одно,
    а вышло другое, и молча расходиться с тем, что человек только что прочитал
    в таблице, нельзя. Теперь обе половины отчёта собираются в одном месте,
    чтобы Qt, Tkinter и консоль говорили одно и то же.

    Пропавший журнал отмены назван отдельной строкой. Раньше он лежал в общем
    списке неудач и печатался под заголовком «Не переехали» — при том, что
    переехали все до одного файла, а «журнал отмены» и не файл вовсе. Само
    последствие при этом терялось среди чужих строк, а оно тут единственное и
    вполне определённое: файлы разложены, но вернуть их назад больше нечем —
    «🕘 История» об этой сортировке не знает.
    """
    parts = [f"Перемещено: {result.moved}, ошибок: {len(result.errors)}"]
    if result.errors:
        parts.append("Не переехали:\n" + listing(result.errors, limit))
    if result.notes:
        parts.append("Легли под другим именем:\n" + listing(result.notes, limit))
    if result.undo_failed:
        parts.append(
            "Отменить эту сортировку не выйдет: журнал отмены не записан "
            f"({result.undo_failed}).")
    return "\n\n".join(parts)
