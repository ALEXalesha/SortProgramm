"""Выполнение плана перемещений: dry-run / apply, лог отмены, чистка папок."""
from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from .config import Config, folder_key, folder_keys
from .planner import Move, external_3d_path
from .util import read_text


@dataclass
class Result:
    planned: int = 0
    moved: int = 0
    skipped: int = 0
    errors: list[tuple[str, str]] = field(default_factory=list)
    # Оговорки: файл переехал, но не совсем так, как обещал план.
    notes: list[tuple[str, str]] = field(default_factory=list)
    undo_log: Path | None = None
    # Почему не записался журнал отмены. Пустая строка — записался.
    #
    # Отдельно от `errors` нарочно. Там лежат файлы, которые остались лежать в
    # загрузках, и отчёт печатает их под заголовком «Не переехали». Незаписанный
    # журнал не файл и никуда не переезжал: все файлы как раз доехали, а нет
    # только возможности вернуть их назад. Попав в общий список, он и врал
    # заголовком, и завышал счёт: «Перемещено: 7, ошибок: 1» на семи из семи
    # успешно переехавших файлов.
    undo_failed: str = ""


def _vacate_first(moves: list[Move]) -> list[Move]:
    """Ставит каждого впереди тех, кому он загораживает папку назначения.

    Файл `Медиа` без расширения — обычный файл, и план у него правильный:
    уезжает в `Others/Misc`, как всё неопознанное. Но пока он лежит в корне,
    папки `Медиа` там быть не может, и `mkdir` для `Медиа/Videos` падает с
    `[WinError 183]`. Выполнялся план в том порядке, в каком его построили, а
    порядок этот задан именами файлов — то есть попадёт ли `клип.mp4` до или
    после виновника, решает алфавит.

    Отчёт в таком случае честный, но говорит про папку назначения, которую не
    создать, а не про файл, лежащий рядом и мешающий: связать одно с другим,
    глядя на `[WinError 183]`, нельзя. Со следующей уборки всё проходит само —
    виновник к тому времени уехал, — и это тоже плохо: поломка, которая
    исчезает при повторе, выглядит случайной.

    Уступать дорогу приходится по цепочке, и одного разворота на это не хватало.
    Раньше здесь стояла устойчивая сортировка «сначала все виновники, потом
    все остальные»: она разводит виновника и пострадавшего, но между собой
    виновников не упорядочивает никак — их взаимный порядок оставался
    алфавитным. Достаточно двух: файл `3D` едет в `Others/Misc/3D`, файл
    `Others` — в `Others/Misc/Others`, и `3D` по алфавиту первый. `mkdir` для
    `Others/Misc` натыкается на файл `Others`, который ещё никуда не уехал, —
    и `[WinError 183]` возвращается ровно там, откуда его выгоняли, только
    поводом теперь второй виновник, а не первый.

    Поэтому порядок здесь не сортировка, а обход зависимостей: перед каждым
    перемещением выпускаем те, чьи файлы стоят на пути его папки назначения, —
    и так далее вглубь. Цепочка короткая по своей природе: у назначения всего
    две значащих ступени (`Категория/Тип`), а `guard` держит на случай, если
    двое загородили дорогу друг другу — такой узел не развязать перестановкой,
    и крутиться в нём бесконечно незачем.

    Загородить дорогу можно и саму цель, не только папку над ней, и этот случай
    разбирается тем же обходом. `заметка.txt` из корня едет в
    `Медиа/Documents/заметка.txt`, а лежащая там тёзка по новым правилам уезжает
    в `Учёбу` — цель освободится, надо лишь пропустить тёзку вперёд. Пока обход
    спрашивал только про папки над целью, порядок тут решал алфавит: успел
    уехать первым — всё сошлось, не успел — `apply` находил путь занятым и клал
    файл рядом под номером ` (1)`. Планировщик к тому же и сам приписывал этот
    номер заранее (`planner._dedup`), так что половины починки не хватало ни
    той, ни другой: имя выбирает план, а освобождает дорогу выполнение.

    Всё, что чужих путей не занимает, идёт как шло: без виновников обход просто
    перекладывает список по порядку. Свободное имя `apply` подбирает заново
    перед каждым перемещением (`_free_name`), так что перестановка ничьё имя не
    путает — а если освободить дорогу не вышло (двое загородили её друг другу,
    перемещение упало), он же и подберёт соседнее имя, назвав это оговоркой.

    Своей собственной цели перестановка не помогает: файл `Others` уезжает в
    `Others/Misc/Others`, то есть занимает путь, который надо создать для него
    же, и подвинуть его вперёд некуда. Этот случай разбирает `apply` — он
    отводит такой файл в сторону под свободным именем.
    """
    by_src: dict[Path, Move] = {mv.src: mv for mv in moves}
    ordered: list[Move] = []
    done: set[int] = set()

    def release(mv: Move, guard: set[int]) -> None:
        if id(mv) in done or id(mv) in guard:
            return
        guard.add(id(mv))
        for occupied in (mv.dst, *mv.dst.parents):
            blocker = by_src.get(occupied)
            if blocker is not None and blocker is not mv:
                release(blocker, guard)
        guard.discard(id(mv))
        done.add(id(mv))
        ordered.append(mv)

    for mv in moves:
        release(mv, set())
    return ordered


def _blocked_by(dst: Path) -> Path | None:
    """Файл, занявший путь одной из папок под `dst`. None — таких нет.

    Ищем сверху вниз и отдаём первый: чинить надо его, всё остальное под ним
    даже не начиналось.
    """
    for step in reversed(dst.parents):
        try:
            if step.exists() and not step.is_dir():
                return step
        except OSError:
            return None
    return None


def _why_failed(exc: OSError, dst: Path) -> str:
    """Причина неудачи словами. Про занятый файлом путь говорит отдельно.

    `[WinError 183] Невозможно создать файл, так как он уже существует` — и
    дальше путь папки назначения. Читается это как «папка уже есть, и потому
    мешает», то есть ровно наоборот: папки как раз нет, а на её месте лежит
    файл с тем же именем. Имя у них одно, так что отличить одно от другого по
    строке отчёта нельзя ничем.

    В загрузках такой виновник всегда стоит в самом плане (файл `Медиа` едет в
    `Others/Misc`), и `_vacate_first` пропускает его вперёд — с этой стороны
    беда лечится сама. Во внешней папке 3D она не лечится никогда: файл без
    расширения `plan_3d_folder` не трогает нарочно, класть его некуда. Значит
    `All_3d/gcode` не создать ни в этот раз, ни в следующий, и каждая уборка
    роняет все `.gcode` до одного — при том, что виновник лежит на виду и
    чинится переименованием за десять секунд.

    Двигать его сами не вправе: его нет в таблице плана, а эта программа не
    двигает того, чего не показала. Поэтому просто называем поимённо.
    """
    blocker = _blocked_by(dst)
    if blocker is None:
        return str(exc)
    return (f"папку «{blocker.name}» не создать — этот путь занят файлом: "
            f"{blocker}. Переименуй или убери его, и файл переедет.")


def apply(moves: list[Move], config: Config, dry_run: bool = True) -> Result:
    result = Result(planned=len(moves))
    if dry_run:
        return result

    performed: list[dict[str, str]] = []
    for mv in _vacate_first(moves):
        # Куда файл отведён в сторону, если он занимал путь собственной цели.
        # None — не отводили.
        aside: Path | None = None
        try:
            if not mv.src.exists():
                raise FileNotFoundError(f"нет файла: {mv.src}")
            source = mv.src
            if mv.src in mv.dst.parents:
                # Файл занял путь, который надо создать для него же: `Others`
                # без расширения едет в `Others/Misc/Others`. Перестановка
                # (`_vacate_first`) тут бессильна — двигать вперёд некого, — и
                # `mkdir` падал с `[WinError 183]` не только на нём, а на всей
                # категории разом: ни один файл, которому место в `Others`, не
                # переезжал. Отчёт при этом называл папку назначения, которую
                # не создать, а не файл, лежащий рядом и мешающий, — связать
                # одно с другим было нельзя, и со следующей уборки ничего не
                # менялось: виновник-то остался на месте.
                #
                # Отводим его в сторону под свободным именем, освобождаем путь,
                # а в журнал отмены пишем исходное имя — откат вернёт файл
                # именно туда, откуда его взяли.
                aside = _free_name(mv.src, as_dir=mv.src.is_dir())
                shutil.move(str(mv.src), str(aside))
                source = aside
            mv.dst.parent.mkdir(parents=True, exist_ok=True)
            # Свободное имя planner подбирал по состоянию на момент плана, а
            # между «Очистить» и «Применить» проходит сколько угодно времени.
            # Занятую за это время цель `shutil.move` затирает молча (файл) или
            # вкладывает в неё (папка) — и то и другое снаружи выглядит как
            # успешная сортировка. Проверяем ещё раз, прямо перед перемещением.
            dst = _free_name(mv.dst, as_dir=source.is_dir())
            shutil.move(str(source), str(dst))
            # Оговорку ставим только после того, как перемещение прошло. Раньше
            # она писалась заранее, и упавший `shutil.move` (файл открыт другой
            # программой, кончилось место) давал отчёт, который спорит сам с
            # собой: один и тот же файл стоял и в «Не переехали», и в «Легли под
            # другим именем». Человек шёл искать `клип (1).mp4`, которого нет.
            if dst != mv.dst:
                result.notes.append((
                    str(mv.src),
                    f"в цели уже есть «{mv.dst.name}», положили как «{dst.name}»"))
            performed.append({"src": str(mv.src), "dst": str(dst)})
            result.moved += 1
        except OSError as exc:
            # Отведённый в сторону файл возвращаем на место: иначе неудача на
            # полпути оставила бы его лежать под именем `Others (1)`, которого
            # никто не просил и о котором в отчёте не сказано ни слова.
            place = mv.src
            if aside is not None and aside.exists():
                # Возврат не проходил никогда, и проверка «путь свободен» была
                # тут виновата сама: `mkdir` для `Others/Misc` создаёт и саму
                # `Others`, то есть занимает папкой ровно то имя, куда файл надо
                # вернуть. `mv.src.exists()` после этого всегда правда, и вся
                # ветка возврата стояла мёртвой — как раз в том случае, ради
                # которого её и писали.
                #
                # Каркас этот наш и создан секунду назад: до отвода в сторону по
                # этому пути лежал файл, а больше его создать некому. Убираем
                # его тем же способом, каким убирает откат, и только пустой.
                _cleanup_emptied([{"src": str(mv.dst), "dst": str(aside)}], config)
                if not mv.src.exists():
                    try:
                        shutil.move(str(aside), str(mv.src))
                    except OSError:
                        pass
                if aside.exists():
                    # Файл так и лежит под придуманным именем. Называть в отчёте
                    # исходный путь значит отправить человека искать его там,
                    # где его нет: он прочтёт про `Others`, а на диске лежит
                    # `Others (1)`, и связать одно с другим нечем — имя
                    # придумала сама программа и нигде его не назвала. Откат про
                    # место говорит правду давно («отведённый в сторону лежит
                    # уже не по тому пути, который записан в журнале»); здесь
                    # отчитывался тот, кто при перемещении не присутствовал.
                    place = aside
            result.errors.append((str(place), _why_failed(exc, mv.dst)))

    # Пустой журнал — это запись «0 файлов» в истории, которая ничего не
    # откатывает. Когда двигать было нечего, истории об этом знать незачем.
    if performed:
        try:
            result.undo_log = _write_undo_log(performed, config)
        except OSError as exc:
            # Файлы уже переехали, а вернуть их назад теперь нечем. Молчать об
            # этом нельзя: снаружи всё выглядит как обычная успешная сортировка.
            #
            # И сказать надо своими словами, а не через список неудавшихся
            # перемещений, куда это складывали раньше. Печатается тот список
            # под заголовком «Не переехали», и оба его слова тут неправда:
            # переехали все до одного, а «журнал отмены» — не файл. Счёт ошибок
            # он завышал заодно, а по нему окно решает, каким окном отчитаться.
            result.undo_failed = str(exc)
    _cleanup_emptied(performed, config)
    return result


def _write_undo_log(performed: list[dict[str, str]], config: Config) -> Path:
    """Пишет журнал отмены и возвращает путь к нему.

    Имя журнала — метка времени с точностью до секунды, и две сортировки подряд
    укладываются в одну секунду запросто: нажал «Применить», поправил галочку,
    нажал снова. Занятое имя поэтому не перезаписываем, а дополняем номером —
    иначе прошлый журнал исчезает вместе с возможностью откатить ту сортировку.
    """
    log_dir = Path(config.downloads_path) / ".sorter"
    log_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_path = log_dir / f"undo_{stamp}.json"
    serial = 2
    while log_path.exists():
        log_path = log_dir / f"undo_{stamp}_{serial}.json"
        serial += 1
    log_path.write_text(json.dumps(performed, ensure_ascii=False, indent=2), encoding="utf-8")
    return log_path


def _is_program_folder(folder: Path, managed: set[str], external: Path | None) -> bool:
    """Папку с таким именем создаёт сама программа — и сама уберёт, когда опустеет.

    Своя папка — это категория или тип из `managed_folders`, а во внешней папке
    3D ещё и подпапка с именем расширения: `All_3d/gcode` создаёт `plan_3d_folder`,
    но в `managed_folders` такого имени нет и быть не должно — там категории, а
    не расширения.

    Спрашивают об этом двое и о разном: уборка решает, что снести (`_cleanup_emptied`),
    а откат — ждать ему освобождения пути или класть файл рядом под номером
    (`undo`). Ответ обязан быть один. Разойдясь, они начнут спорить о судьбе
    одной и той же папки: уборка её снесёт, а откат к тому времени уже решит,
    что она стоит навсегда, и переименует файл насовсем.
    """
    return folder_key(folder.name) in managed or folder.parent == external


def _cleanup_emptied(performed: list[dict[str, str]], config: Config) -> None:
    """Убирает папки, которые опустели именно из-за этого прогона.

    Раньше чистка шла по всему списку `managed_folders` — и сносила любую пустую
    папку с подходящим именем, даже если пользователь создал её сам и программа
    к ней не прикасалась. Теперь отталкиваемся от того, откуда реально уносили
    файлы, и поднимаемся вверх, пока папки пустые и принадлежат программе.

    Своя папка — это категория или тип из `managed_folders`, а во внешней папке
    3D ещё и подпапка с именем расширения: `All_3d/gcode` создаёт сама
    программа (`plan_3d_folder`), но в `managed_folders` такого имени нет и
    быть не должно — это расширения, а не категории. Из-за этого откат
    возвращал файлы из All_3d, а пустые `gcode`, `stl`, `3mf` оставлял лежать
    навсегда: та самая половина отмены, ради которой уборку и добавляли.

    Вверх поднимаемся до корня загрузок или до самой папки 3D — их не трогаем
    никогда, это чужая территория, а не созданный программой каркас.

    Своё имя опознаётся через `folder_key`, как и при обходе: `Медиа` и `медиа`
    на Windows — одна папка, и уборка спотыкалась о регистр ровно там же, где
    спотыкался `scanner`.
    """
    root = Path(config.downloads_path)
    external = external_3d_path(config)
    stop = {root} if external is None else {root, external}
    managed = folder_keys(config.managed_folders)
    for entry in performed:
        folder = Path(entry["src"]).parent
        while (folder not in stop and folder.is_dir()
               and _is_program_folder(folder, managed, external)):
            try:
                if any(folder.iterdir()):
                    break
                folder.rmdir()
            except OSError:
                break
            folder = folder.parent


def _free_name(path: Path, as_dir: bool | None = None) -> Path:
    """Свободное имя рядом с занятым: ` (1)`, ` (2)`…

    У папки расширения нет, но точки в имени бывают
    (`zapret-discord-youtube-1.9.2`), поэтому номер к ней приписывается
    к имени целиком, а не перед последней точкой.

    `as_dir` — папку ли мы кладём. По умолчанию смотрим на то, что уже лежит
    по этому пути, и обычно этого хватает: занимает место обычно такой же
    объект. Но файл может упереться и в папку с тем же именем — тогда номер
    надо ставить по природе того, что кладём (`клип (1).mp4`), а не того, что
    мешает (`клип.mp4 (1)`).
    """
    if not path.exists():
        return path
    if as_dir is None:
        as_dir = path.is_dir()
    stem, suffix = (path.name, "") if as_dir else (path.stem, path.suffix)
    i = 1
    while True:
        candidate = path.with_name(f"{stem} ({i}){suffix}")
        if not candidate.exists():
            return candidate
        i += 1


def entries_of(raw) -> list[dict[str, str]]:
    """Оставляет из журнала только пары «откуда/куда».

    Журнал пишет программа, но лежит он в папке пользователя: правка руками,
    оборванная запись, чужой файл под тем же именем. Всё, что не похоже на
    пару путей, дальше не пускаем — иначе на такой записи падает и откат, и
    окно истории.
    """
    if not isinstance(raw, list):
        return []
    good: list[dict[str, str]] = []
    for entry in raw:
        if not isinstance(entry, dict):
            continue
        src, dst = entry.get("src"), entry.get("dst")
        if isinstance(src, str) and isinstance(dst, str) and src and dst:
            good.append({"src": src, "dst": dst})
    return good


def undo(
    undo_log: Path | str,
    config: Config | None = None,
    settled: list[dict[str, str]] | None = None,
) -> list[tuple[str, str]]:
    """Возвращает файлы на исходные места. Отдаёт список оговорок.

    `settled` — записи, с которыми откат закончил: файл сдвинулся с нового
    места, и делать по этой записи больше нечего. Список тот же по устройству,
    что `problems` у разбора настроек, и нужен он ровно одному читателю —
    `history.undo_operation`, который решает, чему остаться в журнале.

    Спрашивать об этом файловую систему после отката нельзя, и это была
    настоящая поломка, а не мелочь. «Файл вернулся» проверялось по двум путям:
    пусто по новому и занято по исходному. Но занятость пути ничего не значит —
    имена в этой программе повторяются, на том и держится вся возня с номерами
    ` (1)`. Сортировка сплошь и рядом строит цепочку «уступи дорогу»
    (`planner._dedup`, `_vacate_first`): новая `заметка.txt` из корня едет
    туда, откуда уезжает тёзка. Откат возвращает обоих верно — и по новому пути
    первой записи стоит та самая тёзка, вернувшаяся к себе домой. Путь занят по
    праву и совсем другим файлом, а выглядит это как «не вернулся».

    Журнал после такого отката не стирался, и сортировка оставалась в
    «🕘 Истории» как неоткатанная. Второй откат по ней брал файл, лежащий по
    этому пути СЕЙЧАС, и уносил его в корень под именем `заметка (1).txt`: он
    ломал раскладку, которую первый откат только что восстановил, — и делал
    это кнопкой, которая обещает вернуть всё как было.

    Кто откат выполнял, тот про каждую запись и знает точно. Записи, до
    которых дело не дошло (журнал не прочитался, файла по новому пути нет,
    перемещение упало), сюда не попадают — и остаются в журнале, чтобы цепочку
    можно было доиграть позже.

    Если исходный путь к моменту отката снова занят, `shutil.move` повёл бы себя
    коварно: папку он положил бы ВНУТРЬ одноимённой (`claude-usage/claude-usage`),
    а файл мог бы затереть. Поэтому занятый путь не трогаем — возвращаем рядом,
    под свободным именем, и сообщаем об этом наверх. Молчаливое вложение хуже
    любой ошибки: снаружи кажется, что откат прошёл, а данные перепутаны.

    `config` нужен, чтобы убрать за собой папки, опустевшие из-за отката. Без
    него откат возвращал файлы, но оставлял в загрузках весь каркас из папок
    программы — снаружи это выглядело как отмена наполовину.

    Про файл, которого по новому пути уже нет, тоже говорим вслух. Унесли
    руками, переименовали, удалили — вернуть нечего, и раньше такая запись
    просто пропускалась. Отменяя сортировку, где так вышло со всеми файлами,
    человек соглашался на «Вернуть 7 файлов?» и не получал ни файлов, ни
    единого слова, а запись при этом исчезала из истории — то есть и
    разбираться потом было уже не с чем.
    """
    log_path = Path(undo_log)
    try:
        entries = json.loads(read_text(log_path))
    except (OSError, ValueError) as exc:
        # Записи внутри журнала разбираются осторожно (`entries_of`), а сам файл
        # читался напрямую: на оборванной записи `json.loads` бросает ValueError,
        # который окно истории не ловит, — и программа падала целиком вместо
        # того, чтобы сказать, что откатывать нечем.
        #
        # Кодировку разбирает общий декодер: журнал лежит в папке пользователя,
        # и открыть его в Блокноте — обычное дело, когда откат чем-то не
        # устроил. Сохранение «в UTF-8 с BOM» после этого делало журнал
        # нечитаемым, а вместе с ним пропадала и запись из «🕘 Истории».
        return [(str(log_path), f"журнал отмены не читается: {exc}")]

    notes: list[tuple[str, str]] = []
    for entry in reversed(entries_of(entries)):
        src, dst = Path(entry["src"]), Path(entry["dst"])
        if not dst.exists():
            notes.append((str(dst), "возвращать нечего: файла тут больше нет"))
            continue
        source = dst
        if src in dst.parents and config is not None:
            # Файл лежит ВНУТРИ папки, которой должен снова стать: `Others` без
            # расширения уехал в `Others/Misc/Others`, и `apply` для этого
            # отводил его в сторону. Обратный ход тот же, только задом наперёд:
            # вынимаем файл из этого каркаса под свободным именем, даём уборке
            # снести опустевшие `Others/Misc` и `Others`, и лишь потом кладём
            # на место. Без этого путь занят собственной папкой файла, и откат
            # возвращает его как `Others (1)` — то есть обещание «вернём как
            # было» не выполняется ровно в том случае, ради которого в `apply`
            # и заведён обход.
            aside = _free_name(src, as_dir=dst.is_dir())
            try:
                shutil.move(str(dst), str(aside))
            except OSError as exc:
                notes.append((str(dst), str(exc)))
                continue
            _cleanup_emptied([{"src": str(dst), "dst": str(aside)}], config)
            source = aside
        # `is_dir` тут не придирка: ждать имеет смысл только папку — её создала
        # программа и она же уберёт, когда та опустеет. Тёзка-ФАЙЛ с тем же
        # именем (скачали второй `Медиа`, пока сортировка лежала в истории) не
        # денется никуда, и отказ вернуть означал бы, что файл не вернётся
        # вовсе. Опознание идёт по имени, поэтому спросить, что там лежит на
        # самом деле, обязательно.
        if src.is_dir() and config is not None and _is_program_folder(
                src, folder_keys(config.managed_folders), external_3d_path(config)):
            # Исходное место занято папкой, которую создала СОСЕДНЯЯ сортировка —
            # та, что прошла позже и в этом журнале не значится. Файл и папка под
            # одним именем не уживаются никогда, и раньше файл ложился рядом
            # номером (`Медиа (1)`), а запись уходила из журнала: «закончили».
            #
            # Закончили неправдой. Папку эту программа создала сама и сама же
            # снесёт, как только её опустошит откат более поздней сортировки, —
            # то есть место освободится, а файл так и останется переименованным,
            # и записи, по которой его можно вернуть, больше нет. Оговорка при
            # этом честная, но чинить её человеку нечем.
            #
            # Значит откат не бессилен, а всего лишь пришёл рано. Оставляем
            # запись в журнале и говорим, в каком порядке отменять: ровно так же
            # программа поступает с любым другим файлом, который не лёг туда,
            # откуда его унесли (`history.undo_operation`).
            #
            # Чужая папка на этом месте — случай другой: её никто не уберёт, и
            # ждать нечего, поэтому там по-прежнему кладём рядом под номером.
            if source != dst:
                # Файл уже отведён в сторону — вернём его туда, где он лежал.
                # Иначе повторный откат будет искать его по записи в журнале и
                # не найдёт: он останется в корне под именем, которого никто не
                # просил, а запись станет «возвращать нечего».
                try:
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(source), str(dst))
                except OSError as exc:
                    notes.append((str(source), _why_failed(exc, dst)))
                    continue
            notes.append((
                str(src),
                f"путь занят папкой «{src.name}» — её создала сортировка, "
                "сделанная позже. Отмени сначала её, и файл вернётся на место."))
            continue
        target = src
        if src.exists():
            # Номер ставим по природе того, что возвращаем, а не того, что
            # заняло место: иначе видео, упёршееся в папку `клип.mp4`, вернётся
            # как `клип.mp4 (1)` — расширение перестало быть последним, и файл
            # больше не открывается двойным щелчком.
            target = _free_name(src, as_dir=source.is_dir())
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(source), str(target))
        except OSError as exc:
            # Про место говорим то, где файл лежит на самом деле: отведённый в
            # сторону лежит уже не по тому пути, который записан в журнале.
            #
            # Про путь, занятый файлом, — теми же словами, что и `apply`: папку
            # на обратном пути создавать приходится точно так же, и `[WinError
            # 183]` читается здесь так же наоборот.
            notes.append((str(source), _why_failed(exc, target)))
        else:
            # Про новое имя говорим только когда файл под ним и правда лежит.
            # Заранее поставленная оговорка после упавшего `shutil.move`
            # называла имя, которого на диске нет, — и это в том самом отчёте,
            # ради которого откат вообще отчитывается.
            if target != src:
                notes.append((str(src), f"путь занят, вернули как «{target.name}»"))
            if settled is not None:
                settled.append(entry)
            came_back = {"src": str(source), "dst": str(target)}
            if config is not None:
                # Откат опустошает ровно те же папки, которые наполнила
                # сортировка, поэтому и убирается тем же способом — от места,
                # откуда унесли файл, вверх, пока папки пустые и принадлежат
                # программе.
                #
                # Убираем по ходу, а не одной уборкой в конце, и это не мелочь.
                # Файл, уступивший дорогу собственной категории (`Медиа` без
                # расширения рядом с `клип.mp4`), уезжает первым, а
                # возвращается последним — и к его очереди папка `Медиа`,
                # созданная той же сортировкой, ещё стояла пустая на его месте.
                # Путь занят, файл ложился рядом как `Медиа (1)`, и откат,
                # который обещает вернуть всё как было, оставлял вместо файла
                # переименованную копию. Оговорку он при этом честно называл —
                # но чинить её человеку пришлось бы руками, а поводом была
                # пустая папка, которую всё равно предстояло убрать.
                _cleanup_emptied([came_back], config)
    return notes
